// DocsURL is where every setting is documented.
const DocsURL = "https://github.com/esacteksab/gh-anchor#configuration"

// field is one key = value line of a table.
type field struct {
	key   string
	value string // already rendered as TOML
}

// Render writes the config: a table for every image, package and ARG with every
// setting spelled out. gh-anchor only updates what is listed here. Deselected items
// get skip = true; ARGs a lookup disproved are written commented out. Version-like
// ARGs without a detected datasource are listed as comments.
func Render(p *Plan) string {
	var b strings.Builder
	fmt.Fprintf(
		&b,
		"# gh-anchor configuration, generated by `gh anchor init` from %s.\n",
		strings.Join(p.Files, ", "),
	)
	b.WriteString(
		"# gh-anchor only updates what is listed here. Image and package tables record the\n",
	)
	b.WriteString(
		"# tag, digest, version and hash in the Dockerfile; gh-anchor keeps them current.\n",
	)
	fmt.Fprintf(&b, "# Every setting is described at %s\n", DocsURL)

	for _, section := range []string{SectionImages, SectionPackages, SectionArgs} {
		for _, s := range p.Suggestions {
			if s.Section == section {
				b.WriteString("\n")
				writeTable(&b, s)
			}
		}
	}

	if len(p.Unmatched) > 0 {
		b.WriteString(
			"\n# ARGs named like versions (*VERSION*, *_SHA, *_COMMIT) whose source couldn't be\n",
		)
		b.WriteString(
			"# detected. Add an [args.NAME] table with a datasource for any gh-anchor should update:\n",
		)
		for _, u := range p.Unmatched {
			fmt.Fprintf(&b, "#   ARG %s=%s (%s:%d)\n", u.Name, u.Value, u.Where.File, u.Where.Line)
		}
	}
	return b.String()
}

// describe is the one-line description of a suggestion, e.g.
// "COPY --from=golang:1.26.10@sha256:… (Dockerfile:144)".
func describe(s Suggestion) string {
	var what string
	switch s.Section {
	case SectionArgs:
		what = "ARG " + s.Name + "=" + s.Current
	case SectionImages:
		switch {
		case s.Instr == "COPY":
			what = "COPY --from=" + s.Current
		case s.Stage != "":
			what = "FROM " + s.Current + " AS " + s.Stage
		default:
			what = "FROM " + s.Current
		}
	case SectionPackages:
		what = "RUN " + s.Name + "@" + s.Current
		if s.Manager != "" {
			what = "RUN " + s.Manager + " … " + s.Name + "@" + s.Current
		}
	}
	return shortenDigest(what) + " (" + SortedLocations(s.Where) + ")"
}

func writeTable(b *strings.Builder, s Suggestion) {
	b.WriteString("# " + describe(s) + "\n")
	if s.Reason != "" {
		b.WriteString("# Detected: " + s.Reason + "\n")
	}
	for _, n := range s.Notes {
		b.WriteString("# " + capitalize(n) + "\n")
	}

	fields := fieldsFor(s)
	prefix := ""
	switch {
	case s.Rejected:
		b.WriteString("# Not added because the lookup failed. Uncomment to use it anyway.\n")
		prefix = "# "
	case !s.Selected:
		b.WriteString(
			"# Deselected in `gh anchor init`: skip = true, so gh-anchor leaves it alone.\n",
		)
	}

	b.WriteString(prefix + "[" + s.Key() + "]\n")
	width := 0
	for _, f := range fields {
		width = max(width, len(f.key))
	}
	for _, f := range fields {
		fmt.Fprintf(b, "%s  %-*s = %s\n", prefix, width, f.key, f.value)
	}
}

// fieldsFor returns every setting of a suggestion, defaults included, in
// documentation order.
func fieldsFor(s Suggestion) []field {
	var fs []field
	str := func(k, v string) { fs = append(fs, field{key: k, value: fmt.Sprintf("%q", v)}) }
	boolean := func(k string, v bool) { fs = append(fs, field{key: k, value: strconv.FormatBool(v)}) }
	switch s.Section {
	case SectionArgs:
		a := s.Arg
		str("datasource", a.Datasource)
		switch a.Datasource {
		case config.DatasourceNPM:
			str("package", a.Package)
		case config.DatasourceDocker:
			str("image", a.Image)
		case config.DatasourceNodeVersion:
			boolean("lts", a.LTS)
		case config.DatasourceGitHubTags, config.DatasourceGitHubReleases:
			str("repo", a.Repo)
		case config.DatasourceGitHubCommits:
			str("repo", a.Repo)
			str("track", cmp.Or(a.Track, config.TrackBranch))
			if a.Branch != "" {
				str("branch", a.Branch)
			}
		}
		if a.Datasource != config.DatasourceGitHubCommits || a.Track == config.TrackTags {
			str("target", string(a.Target))
		}
		boolean("bump", a.Bump)
	case SectionImages:
		i := s.Image
		str("image", i.Image)
		str("tag", i.Tag)
		str("digest", i.Digest)
		boolean("fixed-tag", i.FixedTag)
		boolean("lts", i.LTS)
		if i.LTSPattern != "" {
			fs = append(fs, field{key: "lts-pattern", value: tomlLiteral(i.LTSPattern)})
		}
		str("target", string(i.Target))
		boolean("bump", i.Bump)
	case SectionPackages:
		str("version", s.Package.Version)
		str("hash", s.Package.Hash)
		str("target", string(s.Package.Target))
		boolean("bump", s.Package.Bump)
	}
	boolean("skip", !s.Selected)
	return fs
}

// tomlLiteral renders s as a TOML literal string ('...') when possible, so regular
// expressions don't need their backslashes doubled.
func tomlLiteral(s string) string {
	if !strings.ContainsAny(s, "'\n\r") {
		return "'" + s + "'"
	}
	return fmt.Sprintf("%q", s)
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// digestTailRe matches all but the first 12 hex digits of a sha256 digest.
var digestTailRe = regexp.MustCompile(`(sha256:[0-9a-f]{12})[0-9a-f]{52}`)

// shortenDigest abbreviates "sha256:<64 hex>" to 12 hex digits for comments.
func shortenDigest(s string) string {
	return digestTailRe.ReplaceAllString(s, "$1…")
}
